#!/usr/bin/env python3
"""Exports game_folder/levels/*.lvl (binary LevelF structs) into web/index.html for the browser version."""
import glob, json, os, struct

FMT = '<i9f5f3f3ff?255s255sx3f3f3f3fii255sx6f3f9f9f'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def cstr(b):
    return b.split(b'\0', 1)[0].decode('utf-8', 'replace')

levels = []
for path in sorted(glob.glob(os.path.join(ROOT, 'game_folder', 'levels', '*.lvl'))):
    data = open(path, 'rb').read()
    if len(data) != struct.calcsize(FMT):
        print('skip', path); continue
    v = list(struct.unpack(FMT, data))
    it = iter(v)
    take = lambda n: [round(next(it), 6) for _ in range(n)]
    lv = {}
    lv['iters'] = next(it)
    lv['params'] = take(9)
    lv['roughness'], lv['metal'], lv['rad'], lv['look'], lv['orbit'] = take(5)
    lv['start'] = take(3); lv['end'] = take(3); lv['kill_y'] = take(1)[0]
    lv['planet'] = bool(next(it))
    lv['name'] = cstr(next(it)); lv['desc'] = cstr(next(it))
    lv['anim'] = take(3)
    lv['light_dir'] = take(3); lv['light_col'] = take(3); lv['bg'] = take(3)
    lv['id'] = next(it); lv['link'] = next(it)
    next(it)  # music
    (lv['ground_force'], lv['air_force'], lv['ground_friction'],
     lv['air_friction'], lv['gravity'], lv['ground_ratio']) = take(6)
    levels.append(lv)

levels.sort(key=lambda l: l['id'])
data = 'const LEVELS = ' + json.dumps(levels, separators=(',', ':')) + ';'
# levels are embedded into index.html so the page works as a single file
html_path = os.path.join(ROOT, 'web', 'index.html')
html = open(html_path, encoding='utf-8').read()
a = html.index('/*LEVELS-BEGIN*/') + len('/*LEVELS-BEGIN*/')
b = html.index('/*LEVELS-END*/')
html = html[:a] + '\n// Generated by tools/export_levels_web.py from game_folder/levels/*.lvl\n' + data + '\n' + html[b:]
open(html_path, 'w', encoding='utf-8').write(html)
print(len(levels), 'levels ->', html_path)
